"""The simulated sources: Veza, Armis, Moveworks and agent telemetry, written in each product's own shapes.
Each is labelled simulated and cites the documentation its shape comes from. Also writes the answer key.

Usage: python -m shopfloor.seed.fixtures
"""

import json
from pathlib import Path

import yaml
from oaaclient.templates import CustomApplication, OAAPermission

from shopfloor.seed.world import DATASETS, World, build
from shopfloor.vocab import ROOT

OUT = ROOT / "data" / "fixtures"
PRIVILEGES = {"read": [OAAPermission.DataRead], "write": [OAAPermission.DataWrite],
              "admin": [OAAPermission.DataRead, OAAPermission.DataWrite, OAAPermission.NonData]}


def _label(source: str, cite: str) -> dict:
    return {"simulated": True, "source": source, "shape_from": cite,
            "note": "Generated by shopfloor.seed.fixtures from the Contoso world. Not real data."}


def veza(w: World) -> dict:
    """One OAA custom application per data platform, built with Veza's own SDK."""
    people = {u["user_name"]: u for u in w.users}
    payloads = {}
    for platform in sorted({d[2] for d in DATASETS}):
        app = CustomApplication(f"contoso-{platform}", application_type="DataPlatform")
        for name, perms in PRIVILEGES.items():
            app.add_custom_permission(name, perms)
        resources = {d[0]: app.add_resource(d[0], resource_type="dataset") for d in DATASETS if d[2] == platform}
        identities = {}
        for g in w.grants:
            if g["dataset"] not in resources:
                continue
            who = g["actor"]
            if who not in identities:
                u = people.get(who)
                if u and u.get("kind") == "agent":
                    ident = app.add_agent(u["title"], unique_id=who, ai_platform="contoso-agent-runtime")
                    ident.add_owner(people[u["owner"]]["email"], owner_type="AzureADUser")
                else:
                    ident = app.add_local_user(who, identities=[u["email"]] if u else [])
                identities[who] = ident
            identities[who].add_permission(g["privilege"], resources=[resources[g["dataset"]]])
        # The access agent provisions on every platform: application-level rights, not dataset grants.
        agent = next(u for u in w.users if u["user_name"] == "svc.access.agent")
        a = app.add_agent(agent["title"], unique_id=agent["user_name"], ai_platform="contoso-agent-runtime")
        a.add_owner(people[agent["owner"]]["email"], owner_type="AzureADUser")
        a.add_permission("admin", apply_to_application=True)
        payloads[platform] = app.get_payload()
    return payloads


def activity(w: World) -> list[dict]:
    """The authority system's history of each grant, as an access-monitoring export would report it: when it
    was granted, when it was revoked (if it was), and its last use. Standing grants made outside any request
    appear too, as granted and never revoked."""
    requested = {(e["actor"], e["dataset"], e["privilege"], e["granted_at"]) for e in w.grant_events}
    events = list(w.grant_events) + [g for g in w.grants
                                     if (g["actor"], g["dataset"], g["privilege"], g["granted_at"]) not in requested]
    return [{"identity": e["actor"], "resource": e["dataset"], "permission": e["privilege"],
             "granted_at": e["granted_at"], "revoked_at": e.get("revoked_at"), "last_used_at": e["last_used_at"]}
            for e in sorted(events, key=lambda e: (e["actor"], e["dataset"], e["privilege"], e["granted_at"]))]


def spans(w: World) -> list[dict]:
    """Agent telemetry in OpenTelemetry's span shape, with GenAI attributes; work.request.id only where the
    agent carried it."""
    out = []
    for k, s in enumerate(w.spans):
        attrs = {"gen_ai.operation.name": "execute_tool", "gen_ai.agent.id": s["agent"],
                 "gen_ai.tool.name": s["operation"], "db.namespace": s["target_system"]}
        if s["request"]:
            attrs["work.request.id"] = s["request"]
        out.append({"trace_id": f"{k:032x}", "span_id": f"{k:016x}", "name": f"execute_tool {s['operation']}",
                    "start_time": s["at"], "resource": {"host.name": s["host"]}, "attributes": attrs})
    return out


def write(w: World | None = None) -> list[Path]:
    w = w or build()
    files = {
        "veza/oaa_payloads.json": {"_label": _label("Veza Open Authorization API", "oaaclient 1.2.1 templates; "
                                                    "https://developer.veza.com/oaa/guide/getting-started"),
                                   "payloads": veza(w)},
        "veza/activity.json": {"_label": _label("Veza access activity (last use per grant)", "simulated export"),
                               "activity": activity(w)},
        "armis/assets_search.json": {"_label": _label("Armis POST /v3/assets/_search",
                                                      "https://dev.armis.com/docs/extracting-device-information"),
                                     "results": w.armis_assets},
        "moveworks/intake.json": {"_label": _label("Moveworks Agent Studio HTTP action payloads", "https://docs."
                                                   "moveworks.com/agent-studio/actions/http-actions/http-action-data-bank"),
                                  "calls": w.moveworks_intake},
        "telemetry/spans.json": {"_label": _label("OpenTelemetry spans from agents (GenAI conventions)",
                                                  "https://opentelemetry.io/docs/specs/semconv/gen-ai/"),
                                 "spans": spans(w)},
        "datasets.json": {"_label": _label("Data catalogue export", "simulated"), "datasets": w.datasets},
    }
    written = []
    for rel, data in files.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(data, indent=1, sort_keys=True, default=str) + "\n")
        written.append(p)
    truth = ROOT / "data" / "truth.yaml"
    truth.write_text("# The answer key. Only the scorer reads this.\n" + yaml.safe_dump(w.truth, sort_keys=False))
    written.append(truth)
    return written


if __name__ == "__main__":
    for p in write():
        print(p.relative_to(ROOT), p.stat().st_size)
